//! `zsh-tool.lock`: the exact commit of every plugin zsh-tool installed.

use std::collections::BTreeMap;
use std::fs;
use std::io::ErrorKind;
use std::path::Path;

use anyhow::{Context, Result, anyhow, bail};
use serde::{Deserialize, Serialize};

use crate::files::write_atomic;
use crate::git::{self, ObjectId};
use crate::plugin::ValidName;
use crate::source::check_url;

const HEADER: &str = "# Generated by zsh-tool; do not edit.\n";
/// `source` value of plugins copied from the registry.
const REGISTRY: &str = "registry";

/// Where a managed plugin comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Source {
    /// `plugins/<name>` of the registry repository.
    Registry,
    /// A Git repository of its own.
    Git(String),
}

impl std::fmt::Display for Source {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Registry => f.write_str(REGISTRY),
            Self::Git(url) => f.write_str(url),
        }
    }
}

/// A managed plugin.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    pub source: Source,
    /// Commit of the plugin repository, or of the registry.
    pub commit: ObjectId,
}

/// The lock file, keyed and written by plugin name.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Lock {
    pub plugins: BTreeMap<String, Entry>,
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct File {
    #[serde(default, rename = "plugin")]
    plugins: Vec<Raw>,
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Raw {
    #[serde(serialize_with = "plain")]
    name: ValidName,
    source: toml::Spanned<String>,
    commit: toml::Spanned<String>,
}

fn plain<S: serde::Serializer>(name: &ValidName, serializer: S) -> Result<S::Ok, S::Error> {
    serializer.serialize_str(&name.0)
}

impl Lock {
    /// Parses a lock file; errors include the line.
    pub fn parse(text: &str) -> Result<Self> {
        let file: File = toml::from_str(text)?;
        let mut plugins = BTreeMap::new();
        for raw in file.plugins {
            let at = |span: std::ops::Range<usize>| line(text, span.start);
            let source = match raw.source.get_ref().as_str() {
                REGISTRY => Source::Registry,
                url => {
                    check_url(url).with_context(|| format!("line {}", at(raw.source.span())))?;
                    Source::Git(url.to_owned())
                }
            };
            let commit = git::parse_id(raw.commit.get_ref())
                .with_context(|| format!("line {}", at(raw.commit.span())))?;
            let name = raw.name.0;
            if plugins
                .insert(name.clone(), Entry { source, commit })
                .is_some()
            {
                bail!("plugin {name} is listed twice");
            }
        }
        Ok(Self { plugins })
    }

    /// Loads `path`; a missing file is an empty lock.
    pub fn load(path: &Path) -> Result<Self> {
        let text = match fs::read_to_string(path) {
            Ok(text) => text,
            Err(err) if err.kind() == ErrorKind::NotFound => return Ok(Self::default()),
            Err(err) => return Err(err).with_context(|| format!("cannot read {}", path.display())),
        };
        Self::parse(&text).with_context(|| format!("invalid lock file {}", path.display()))
    }

    /// The lock file text: one `[[plugin]]` table per plugin, sorted by name.
    pub fn render(&self) -> Result<String> {
        let plugins = self
            .plugins
            .iter()
            .map(|(name, entry)| Raw {
                name: ValidName(name.clone()),
                source: toml::Spanned::new(0..0, entry.source.to_string()),
                commit: toml::Spanned::new(0..0, entry.commit.to_string()),
            })
            .collect();
        let body = toml::to_string(&File { plugins }).map_err(|err| anyhow!(err))?;
        Ok(format!(
            "{HEADER}{}{body}",
            if body.is_empty() { "" } else { "\n" }
        ))
    }

    /// Writes the lock to `path`.
    pub fn save(&self, path: &Path) -> Result<()> {
        write_atomic(path, &self.render()?)
    }
}

/// 1-based line of byte `offset` in `text`.
fn line(text: &str, offset: usize) -> usize {
    text.as_bytes()[..offset.min(text.len())]
        .iter()
        .filter(|&&b| b == b'\n')
        .count()
        + 1
}

#[cfg(test)]
mod tests {
    use super::*;

    const A: &str = "0123456789abcdef0123456789abcdef01234567";
    const B: &str = "89abcdef0123456789abcdef0123456789abcdef";

    fn sample() -> Lock {
        let mut lock = Lock::default();
        lock.plugins.insert(
            "zz".to_owned(),
            Entry {
                source: Source::Registry,
                commit: git::parse_id(A).unwrap(),
            },
        );
        lock.plugins.insert(
            "aa".to_owned(),
            Entry {
                source: Source::Git("https://example.com/a \"b\".git".to_owned()),
                commit: git::parse_id(B).unwrap(),
            },
        );
        lock
    }

    #[test]
    fn renders_sorted_and_parses_back() {
        let lock = sample();
        let text = lock.render().unwrap();
        assert!(text.starts_with(HEADER));
        assert!(text.find("name = \"aa\"").unwrap() < text.find("name = \"zz\"").unwrap());
        assert!(text.contains("source = \"registry\""));
        assert!(text.contains(&format!("commit = \"{A}\"")));
        assert_eq!(lock.render().unwrap(), text, "rendering is stable");
    }

    #[test]
    fn round_trips_valid_lock() {
        let mut lock = sample();
        lock.plugins.get_mut("aa").unwrap().source =
            Source::Git("https://example.com/a.git".to_owned());
        assert_eq!(Lock::parse(&lock.render().unwrap()).unwrap(), lock);
        assert_eq!(
            Lock::parse(&Lock::default().render().unwrap()).unwrap(),
            Lock::default()
        );
    }

    #[test]
    fn rejects_invalid_entries_with_line() {
        let entry = |name: &str, source: &str, commit: &str| {
            format!("[[plugin]]\nname = {name:?}\nsource = {source:?}\ncommit = {commit:?}\n")
        };
        let cases = [
            (entry("../x", "registry", A), "line 2"),
            (entry("x", "http://example.com/x", A), "line 3"),
            (entry("x", "registry", "abc"), "line 4"),
        ];
        for (text, expected) in cases {
            let err = format!("{:#}", Lock::parse(&text).unwrap_err());
            assert!(err.contains(expected), "{text}: {err}");
        }
        let twice = format!("{}{}", entry("x", "registry", A), entry("x", "registry", B));
        assert!(Lock::parse(&twice).is_err());
        assert!(Lock::parse("[[plugin]]\nname = \"x\"\n").is_err());
    }

    #[test]
    fn missing_file_is_empty_and_save_round_trips() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("zsh-tool.lock");
        assert_eq!(Lock::load(&path).unwrap(), Lock::default());
        let mut lock = sample();
        lock.plugins.remove("aa");
        lock.save(&path).unwrap();
        assert_eq!(Lock::load(&path).unwrap(), lock);
        fs::write(&path, "[[plugin]\n").unwrap();
        let err = format!("{:#}", Lock::load(&path).unwrap_err());
        assert!(
            err.contains("zsh-tool.lock") && err.contains("line 1"),
            "{err}"
        );
    }
}
