//! `zsh-tool init zsh`: script generation, fingerprint and cache.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::time::UNIX_EPOCH;

use anyhow::{Context, Result};

use crate::config::{Config, Loaded};
use crate::paths::Paths;
use crate::plugin::{Plugin, Resolved};
use crate::zsh::quote_path;

const VERSION: &str = env!("CARGO_PKG_VERSION");
const CACHE_FILE: &str = "init.zsh";
const COMPDUMP_PREFIX: &str = "zcompdump";

/// Returns the init script, from the cache when it is still valid.
pub fn run(paths: &Paths) -> Result<String> {
    let loaded = Config::load(&paths.config_file)?;
    let search_dirs = paths.plugin_dirs();
    let plugins: Vec<Plugin> = loaded
        .config
        .plugins
        .iter()
        .map(|name| Plugin::resolve(name, &search_dirs))
        .collect();
    let fingerprint = fingerprint(paths, &loaded, &plugins);

    let cache_file = paths.cache_dir.join(CACHE_FILE);
    if let Some(script) = read_cache(&cache_file, fingerprint) {
        return Ok(script);
    }

    let script = generate(paths, &plugins, fingerprint)?;
    // A cache that cannot be written only costs speed: the shell must
    // still start, so report the problem and carry on.
    if let Err(err) = write_cache(&paths.cache_dir, &script) {
        eprintln!("zsh-tool: warning: {err:#}");
    }
    Ok(script)
}

/// Builds the zsh script for the resolved plugins.
pub fn generate(paths: &Paths, plugins: &[Plugin], fingerprint: u64) -> Result<String> {
    let mut out = String::new();
    writeln!(out, "# Generated by zsh-tool {VERSION}; do not edit.")?;
    writeln!(out, "{}", fingerprint_line(fingerprint))?;

    writeln!(out, "\n# Oh My Zsh compatibility")?;
    if let Some(omz) = &paths.omz_dir {
        writeln!(out, "export ZSH={}", quote_path(omz)?)?;
    }
    writeln!(out, "export ZSH_CUSTOM={}", quote_path(&paths.omz_custom)?)?;
    writeln!(
        out,
        "export ZSH_CACHE_DIR={}",
        quote_path(&paths.omz_cache)?
    )?;
    let compdump = paths.cache_dir.join(format!("{COMPDUMP_PREFIX}-"));
    writeln!(
        out,
        "ZSH_COMPDUMP={}\"$ZSH_VERSION\"",
        quote_path(&compdump)?
    )?;
    writeln!(
        out,
        "[[ -d $ZSH_CACHE_DIR/completions ]] || mkdir -p -- \"$ZSH_CACHE_DIR/completions\""
    )?;

    writeln!(out, "\n# fpath")?;
    let mut fpath = Vec::new();
    for plugin in plugins {
        if let Resolved::Legacy { dir, .. } = &plugin.resolved {
            fpath.push(quote_path(dir)?);
        }
    }
    fpath.push("\"$ZSH_CACHE_DIR/completions\"".to_owned());
    fpath.push("$fpath".to_owned());
    writeln!(out, "typeset -gU fpath")?;
    writeln!(out, "fpath=({})", fpath.join(" "))?;

    // Plugins may call compdef before compinit has defined it: record the
    // calls and replay them once completion is initialised.
    writeln!(out, "\n# plugins")?;
    writeln!(out, "typeset -ga _zsh_tool_compdefs")?;
    writeln!(
        out,
        "compdef() {{ _zsh_tool_compdefs+=(\"${{(j: :)${{(@q)@}}}}\") }}"
    )?;
    for plugin in plugins {
        match &plugin.resolved {
            Resolved::Legacy {
                script: Some(script),
                ..
            } => {
                writeln!(out, "# plugin {}", plugin.name)?;
                writeln!(out, "source {}", quote_path(script)?)?;
            }
            Resolved::Legacy { script: None, .. } => {
                writeln!(out, "# plugin {}: completions only", plugin.name)?;
            }
            Resolved::NotFound => {
                writeln!(out, "# plugin {}: not found", comment(&plugin.name))?;
            }
        }
    }

    writeln!(out, "\n# completion")?;
    writeln!(out, "autoload -Uz compinit")?;
    writeln!(out, "compinit -C -d \"$ZSH_COMPDUMP\"")?;
    writeln!(
        out,
        "for _zsh_tool_compdef in $_zsh_tool_compdefs; do eval \"compdef $_zsh_tool_compdef\"; done"
    )?;
    writeln!(out, "unset _zsh_tool_compdef _zsh_tool_compdefs")?;
    Ok(out)
}

/// Keeps user-supplied text on a single comment line.
fn comment(text: &str) -> String {
    text.replace(['\n', '\r'], " ")
}

fn fingerprint_line(fingerprint: u64) -> String {
    format!("# fingerprint: {fingerprint:016x}")
}

/// Hashes everything the generated script depends on: zsh-tool version,
/// configuration, locations, and the location and modification time of
/// every plugin.
pub fn fingerprint(paths: &Paths, loaded: &Loaded, plugins: &[Plugin]) -> u64 {
    let mut hash = Fnv::new();
    hash.field(VERSION.as_bytes());
    hash.field(loaded.source.as_deref().unwrap_or("").as_bytes());
    hash.field(&[u8::from(loaded.source.is_some())]);
    for path in [&paths.cache_dir, &paths.omz_custom, &paths.omz_cache] {
        hash.field(path.as_os_str().as_encoded_bytes());
    }
    let omz = paths.omz_dir.as_deref().unwrap_or(Path::new(""));
    hash.field(omz.as_os_str().as_encoded_bytes());
    for plugin in plugins {
        hash.field(plugin.name.as_bytes());
        match &plugin.resolved {
            Resolved::Legacy { dir, script } => {
                hash.field(dir.as_os_str().as_encoded_bytes());
                hash.field(&mtime(dir).to_le_bytes());
                if let Some(script) = script {
                    hash.field(&mtime(script).to_le_bytes());
                }
            }
            Resolved::NotFound => hash.field(b"not found"),
        }
    }
    hash.finish()
}

/// Modification time in nanoseconds, 0 when unavailable.
fn mtime(path: &Path) -> u128 {
    fs::metadata(path)
        .and_then(|meta| meta.modified())
        .ok()
        .and_then(|time| time.duration_since(UNIX_EPOCH).ok())
        .map_or(0, |since| since.as_nanos())
}

fn read_cache(file: &Path, fingerprint: u64) -> Option<String> {
    let script = fs::read_to_string(file).ok()?;
    (script.lines().nth(1) == Some(fingerprint_line(fingerprint).as_str())).then_some(script)
}

/// Writes the script atomically and drops completion dumps built for the
/// previous script.
fn write_cache(dir: &Path, script: &str) -> Result<()> {
    fs::create_dir_all(dir).with_context(|| format!("cannot create {}", dir.display()))?;
    let file = dir.join(CACHE_FILE);
    let tmp = dir.join(format!("{CACHE_FILE}.{}.tmp", std::process::id()));
    fs::write(&tmp, script).with_context(|| format!("cannot write {}", tmp.display()))?;
    fs::rename(&tmp, &file).with_context(|| format!("cannot write {}", file.display()))?;

    for entry in fs::read_dir(dir)?.flatten() {
        if entry
            .file_name()
            .to_string_lossy()
            .starts_with(COMPDUMP_PREFIX)
        {
            fs::remove_file(entry.path())
                .with_context(|| format!("cannot remove {}", entry.path().display()))?;
        }
    }
    Ok(())
}

/// 64-bit FNV-1a, stable across builds unlike `std`'s default hasher.
struct Fnv(u64);

impl Fnv {
    fn new() -> Self {
        Self(0xcbf2_9ce4_8422_2325)
    }

    fn write(&mut self, bytes: &[u8]) {
        for &byte in bytes {
            self.0 ^= u64::from(byte);
            self.0 = self.0.wrapping_mul(0x0100_0000_01b3);
        }
    }

    /// Hashes a length-prefixed field so that adjacent fields cannot run
    /// into each other.
    fn field(&mut self, bytes: &[u8]) {
        self.write(&(bytes.len() as u64).to_le_bytes());
        self.write(bytes);
    }

    fn finish(&self) -> u64 {
        self.0
    }
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;

    struct Fixture {
        _root: tempfile::TempDir,
        paths: Paths,
    }

    fn fixture() -> Fixture {
        let root = tempfile::tempdir().unwrap();
        let home = root.path().to_owned();
        fs::create_dir(home.join(".oh-my-zsh")).unwrap();
        let paths = Paths::resolve(|name| (name == "HOME").then(|| home.clone())).unwrap();
        Fixture { _root: root, paths }
    }

    fn add_plugin(paths: &Paths, name: &str, body: &str) -> PathBuf {
        let dir = paths.omz_dir.as_ref().unwrap().join("plugins").join(name);
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join(format!("{name}.plugin.zsh")), body).unwrap();
        dir
    }

    fn write_config(paths: &Paths, text: &str) {
        fs::create_dir_all(paths.config_file.parent().unwrap()).unwrap();
        fs::write(&paths.config_file, text).unwrap();
    }

    #[test]
    fn generates_plugin_lines_in_order() {
        let fx = fixture();
        let git = add_plugin(&fx.paths, "git", "");
        let sudo = add_plugin(&fx.paths, "sudo", "");
        write_config(&fx.paths, "plugins = [\"git\", \"missing\", \"sudo\"]\n");
        let script = run(&fx.paths).unwrap();

        let git_line = format!("source '{}/git.plugin.zsh'", git.display());
        let sudo_line = format!("source '{}/sudo.plugin.zsh'", sudo.display());
        let git_at = script.find(&git_line).expect(&script);
        let missing_at = script.find("# plugin missing: not found").expect(&script);
        let sudo_at = script.find(&sudo_line).expect(&script);
        assert!(git_at < missing_at && missing_at < sudo_at, "{script}");
        assert!(script.contains(&format!(
            "fpath=('{}' '{}' \"$ZSH_CACHE_DIR/completions\" $fpath)",
            git.display(),
            sudo.display()
        )));
    }

    #[test]
    fn defines_compatibility_variables_before_plugins() {
        let fx = fixture();
        add_plugin(&fx.paths, "git", "");
        write_config(&fx.paths, "plugins = [\"git\"]\n");
        let script = run(&fx.paths).unwrap();
        let omz = fx.paths.omz_dir.as_ref().unwrap();
        let zsh_at = script
            .find(&format!("export ZSH='{}'", omz.display()))
            .unwrap();
        assert!(script.contains("export ZSH_CUSTOM="));
        assert!(script.contains("export ZSH_CACHE_DIR="));
        assert!(zsh_at < script.find("source ").unwrap());
    }

    #[test]
    fn runs_compinit_once_after_plugins() {
        let fx = fixture();
        add_plugin(&fx.paths, "git", "");
        write_config(&fx.paths, "plugins = [\"git\"]\n");
        let script = run(&fx.paths).unwrap();
        assert_eq!(script.matches("compinit -C").count(), 1);
        assert!(script.find("source ").unwrap() < script.find("compinit -C").unwrap());
    }

    #[test]
    fn works_without_configuration() {
        let fx = fixture();
        let script = run(&fx.paths).unwrap();
        assert!(script.contains("compinit -C"));
        assert!(!script.contains("source "));
    }

    #[test]
    fn keeps_odd_names_inside_comments() {
        let fx = fixture();
        write_config(&fx.paths, "plugins = [\"a\\nrm -rf ~\"]\n");
        let script = run(&fx.paths).unwrap();
        assert!(
            script.contains("# plugin a rm -rf ~: not found"),
            "{script}"
        );
        assert!(!script.lines().any(|line| line == "rm -rf ~: not found"));
    }

    #[test]
    fn reuses_cache_until_something_changes() {
        let fx = fixture();
        let git = add_plugin(&fx.paths, "git", "");
        write_config(&fx.paths, "plugins = [\"git\"]\n");
        let first = run(&fx.paths).unwrap();
        let cache = fx.paths.cache_dir.join(CACHE_FILE);
        assert_eq!(fs::read_to_string(&cache).unwrap(), first);

        // A hand-edited cache with a matching fingerprint is served as is.
        fs::write(&cache, format!("{first}# marker\n")).unwrap();
        assert!(run(&fx.paths).unwrap().ends_with("# marker\n"));

        // Touching a plugin invalidates the cache.
        let script = git.join("git.plugin.zsh");
        let file = fs::File::options().write(true).open(&script).unwrap();
        file.set_modified(UNIX_EPOCH + std::time::Duration::from_secs(1))
            .unwrap();
        assert!(!run(&fx.paths).unwrap().contains("# marker"));
    }

    #[test]
    fn configuration_change_invalidates_cache() {
        let fx = fixture();
        add_plugin(&fx.paths, "git", "");
        write_config(&fx.paths, "plugins = []\n");
        assert!(!run(&fx.paths).unwrap().contains("plugin git"));
        write_config(&fx.paths, "plugins = [\"git\"]\n");
        assert!(run(&fx.paths).unwrap().contains("# plugin git\n"));
    }

    #[test]
    fn regeneration_removes_completion_dumps() {
        let fx = fixture();
        fs::create_dir_all(&fx.paths.cache_dir).unwrap();
        let dump = fx.paths.cache_dir.join("zcompdump-5.9");
        let compiled = fx.paths.cache_dir.join("zcompdump-5.9.zwc");
        fs::write(&dump, "").unwrap();
        fs::write(&compiled, "").unwrap();
        run(&fx.paths).unwrap();
        assert!(!dump.exists() && !compiled.exists());

        // A cache hit leaves the dump alone.
        fs::write(&dump, "").unwrap();
        run(&fx.paths).unwrap();
        assert!(dump.exists());
    }

    #[test]
    fn unwritable_cache_still_returns_script() {
        let fx = fixture();
        let mut paths = fx.paths.clone();
        let blocker = fx.paths.config_file.with_file_name("not-a-dir");
        fs::create_dir_all(blocker.parent().unwrap()).unwrap();
        fs::write(&blocker, "").unwrap();
        paths.cache_dir = blocker.join("cache");
        assert!(run(&paths).unwrap().contains("compinit -C"));
    }

    #[test]
    fn invalid_configuration_is_an_error() {
        let fx = fixture();
        write_config(&fx.paths, "plugins = [\n");
        assert!(run(&fx.paths).is_err());
    }

    #[test]
    fn fnv_matches_reference_vector() {
        let mut hash = Fnv::new();
        hash.write(b"a");
        assert_eq!(hash.finish(), 0xaf63_dc4c_8601_ec8c);
    }
}
